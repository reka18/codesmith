//! Differential test of the shell permission scanner against real shells.
//!
//! The `shell` tool decides which permission rules apply by scanning a
//! command string statically (`tool::shell_scan`). This test checks that
//! scan against ground truth: each input is run under every installed shell
//! (bash, zsh, `/bin/sh`, dash, the system bash) in a fresh temporary
//! directory whose `PATH` holds only shim executables. A shim logs its argv
//! and does nothing else; Bash's `command_not_found_handle` and Zsh's
//! `command_not_found_handler` log any other name. On macOS the shells run
//! under `sandbox-exec`, which refuses network access, writes outside the
//! temporary directory and executing anything but the shims and shells.
//! Each case runs in a session of its own under a process budget
//! (`RLIMIT_NPROC`, and a sweep once it has more than `CASE_LIMIT`
//! processes); when it ends or times out, everything in its session and
//! below it is stopped, then killed (see `contain`), so a case that forks
//! without end cannot fill the process table or outlive its run. Each case
//! starts with a fresh work dir, home and temporary folder, and the sandbox
//! keeps it from changing the shims or the shells' startup files, so what
//! runs before it in the same slot (which depends on scheduling) cannot
//! change what it does.
//!
//! A run cut short by the deadline or the process budget, one where a fork
//! or a write failed for want of processes or disk space, or one into which
//! a process of an earlier case logged (each record carries the tag of the
//! case that wrote it) is inconclusive: what it found is checked by running
//! the input again, and a clean run decides (see `Run::inconclusive`).
//!
//! Every logged command must be accounted for by the scan: some command or
//! delegated command the scan reports matches a rule `name *` for the logged
//! name, or the scan refused the input (unanalyzable) or flagged it as
//! dynamic (refused whenever a rule could deny), or reported code in
//! another language (`code:perl ...`, see `shell_scan`). Every file the shell itself
//! creates in the work directory must likewise be a write the scan reports
//! (or the scan flags an unknown write target, or the input as dynamic).
//!
//! Inputs come from a curated corpus (`tests/fixtures/shell_differential/
//! corpus.txt`) and a seeded generator composing the same constructs.
//! `CODESMITH_FUZZ_CASES` sets how many generated cases run (default 300),
//! `CODESMITH_FUZZ_SEED` their seed. A generated bypass is printed with its
//! input so it can be added to the corpus.
