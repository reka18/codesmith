fn slots(n: usize) -> (tempfile::TempDir, Vec<Slot>) {
    let dir = tempfile::Builder::new()
        .prefix("codesmith-shdiff")
        .tempdir()
        .unwrap();
    let slots = (0..n)
        .map(|i| Slot::new(dir.path().join(format!("s{i}"))))
        .collect();
    (dir, slots)
}

/// Run `inputs` across the slots in parallel; bypasses per input index.
fn run_all(slots: &[Slot], inputs: &[String]) -> Vec<(usize, Vec<Bypass>)> {
    let shells = installed_shells();
    let next = Mutex::new(0usize);
    let results = Mutex::new(Vec::new());
    std::thread::scope(|scope| {
        for slot in slots {
            let (next, results, shells) = (&next, &results, &shells);
            scope.spawn(move || loop {
                let i = {
                    let mut n = next.lock().unwrap();
                    let i = *n;
                    *n += 1;
                    i
                };
                let Some(input) = inputs.get(i) else {
                    return;
                };
                let found = bypasses(slot, shells, input);
                results.lock().unwrap().push((i, found));
            });
        }
    });
    let mut r = results.into_inner().unwrap();
    r.sort_by_key(|(i, _)| *i);
    r
}

fn workers() -> usize {
    std::thread::available_parallelism()
        .map(|n| n.get())
        .unwrap_or(4)
        .clamp(2, 8)
}

fn report(found: &[Bypass]) -> String {
    let mut s = String::new();
    for b in found {
        s.push_str(&format!("[{}] {} <- {:?}\n", b.shell, b.what, b.input));
    }
    s
}

#[test]
fn shell_differential_corpus() {
    let cases = corpus();
    assert!(cases.len() > 100, "corpus is too small: {}", cases.len());
    let (_dir, slots) = slots(workers());
    let inputs: Vec<String> = cases.iter().map(|c| c.input.clone()).collect();
    let results = run_all(&slots, &inputs);
    let mut unexpected = Vec::new();
    let mut fixed_known = Vec::new();
    for (i, found) in results {
        match (&cases[i].known, found.is_empty()) {
            (None, false) => unexpected.extend(found),
            (Some(_), true) => fixed_known.push(cases[i].input.clone()),
            _ => {}
        }
    }
    assert!(
        unexpected.is_empty(),
        "commands ran that the scan did not report:\n{}",
        report(&unexpected)
    );
    // A known gap that no longer reproduces should lose its `known:` mark
    // (only checked where a sandbox and the shells make the run meaningful).
    if slots[0].profile.is_some() && installed_shells().len() >= 3 {
        assert!(
            fixed_known.is_empty(),
            "known gaps that no longer reproduce: {fixed_known:#?}"
        );
    }
}

