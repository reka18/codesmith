struct Case {
    input: String,
    /// `known: reason` cases document a gap that is deliberately left.
    known: Option<String>,
}

/// Cases separated by lines starting with `%%`; the rest of that line is a
/// comment, `%% known: reason` marks a deliberately left gap.
fn corpus() -> Vec<Case> {
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/shell_differential/corpus.txt");
    let text = std::fs::read_to_string(&path).unwrap();
    let mut out = Vec::new();
    let mut cur: Option<(Vec<&str>, Option<String>)> = None;
    for line in text.split('\n') {
        if let Some(comment) = line.strip_prefix("%%") {
            if let Some((lines, known)) = cur.take() {
                push_case(&mut out, &lines, known);
            }
            let known = comment
                .trim()
                .strip_prefix("known:")
                .map(|r| r.trim().to_string());
            cur = Some((Vec::new(), known));
        } else if let Some((lines, _)) = cur.as_mut() {
            lines.push(line);
        }
    }
    if let Some((lines, known)) = cur.take() {
        push_case(&mut out, &lines, known);
    }
    out
}

fn push_case(out: &mut Vec<Case>, lines: &[&str], known: Option<String>) {
    let mut lines = lines.to_vec();
    while lines.last().is_some_and(|l| l.is_empty()) {
        lines.pop();
    }
    if lines.is_empty() {
        return;
    }
    out.push(Case {
        input: lines.join("\n"),
        known,
    });
}

