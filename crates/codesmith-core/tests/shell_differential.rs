const RS: char = '\u{1e}';
/// Leads a record the not-found handler wrote: a name looked up, not run.
const NOT_FOUND: char = '\u{1}';
const US: char = '\u{1f}';
/// Ends the case tag that leads each record (see [`Slot::run_case`]).
const TAG: char = '\u{2}';
/// The variable a case's tag is passed in.
const CASE_VAR: &str = "CODESMITH_DIFF_CASE";
/// Runs of a shell on an input when a run that found something unaccounted
/// for was inconclusive (see [`Run::inconclusive`]).
const ATTEMPTS: usize = 3;

fn installed_shells() -> Vec<(&'static str, &'static str)> {
    let mut out: Vec<(&str, &str)> = Vec::new();
    for &(label, path) in SHELLS {
        if out.iter().any(|(l, _)| *l == label) || !Path::new(path).exists() {
            continue;
        }
        // `/bin/sh` may be the same program as one already listed.
        let real = std::fs::canonicalize(path).ok();
        if out
            .iter()
            .any(|(_, p)| std::fs::canonicalize(p).ok() == real && label != "sh")
        {
            continue;
        }
        out.push((label, path));
    }
    out
}

/// Processes one case may have before it is ended: a case that forks
/// without end (`command_not_found_handler() { rr|m F; }; nosuch` under
/// Zsh) is swept as soon as the run loop sees it pass this.
const CASE_LIMIT: usize = 64;

/// The hard stop behind [`CASE_LIMIT`], for forks faster than the run loop
/// looks: `RLIMIT_NPROC` counts every process of the user, so the limit is
/// set this far above the count when a case starts. Cases running at once
/// share it, which also keeps several such cases together from going much
/// past it.
const CASE_PROCESSES: usize = 256;

/// Runs take this shared; a test that must see the process table alone
/// takes it exclusively.
static RUNS: std::sync::RwLock<()> = std::sync::RwLock::new(());

/// A live process: `(pid, parent, session, uid)`. Zombies are left out.
type Proc = (i32, i32, i32, u32);

#[cfg(target_os = "macos")]
fn processes() -> Vec<Proc> {
    let mut pids = vec![0i32; 16384];
    let n = unsafe {
        libc::proc_listallpids(pids.as_mut_ptr().cast(), (pids.len() * 4) as libc::c_int)
    };
    pids.truncate(n.max(0) as usize);
    let mut out = Vec::new();
    for pid in pids.into_iter().filter(|&p| p > 0) {
        let mut info: libc::proc_bsdinfo = unsafe { std::mem::zeroed() };
        let size = std::mem::size_of::<libc::proc_bsdinfo>() as libc::c_int;
        let got = unsafe {
            libc::proc_pidinfo(
                pid,
                libc::PROC_PIDTBSDINFO,
                0,
                (&mut info as *mut libc::proc_bsdinfo).cast(),
                size,
            )
        };
        // SZOMB: exited, waiting to be reaped.
        if got != size || info.pbi_status == 5 {
            continue;
        }
        let session = unsafe { libc::getsid(pid) };
        out.push((pid, info.pbi_ppid as i32, session, info.pbi_uid));
    }
    out
}

#[cfg(not(target_os = "macos"))]
fn processes() -> Vec<Proc> {
    use std::os::unix::fs::MetadataExt;
    let mut out = Vec::new();
    let Ok(dir) = std::fs::read_dir("/proc") else {
        return out;
    };
    for e in dir.flatten() {
        let Ok(pid) = e.file_name().to_string_lossy().parse::<i32>() else {
            continue;
        };
        let Ok(stat) = std::fs::read_to_string(e.path().join("stat")) else {
            continue;
        };
        // `pid (comm) state ppid pgrp session ...`; comm may hold spaces.
        let Some(rest) = stat.rsplit_once(')').map(|(_, r)| r) else {
            continue;
        };
        let f: Vec<&str> = rest.split_whitespace().collect();
        if f.len() < 4 || f[0] == "Z" {
            continue;
        }
        let uid = e.metadata().map(|m| m.uid()).unwrap_or(u32::MAX);
        out.push((
            pid,
            f[1].parse().unwrap_or(0),
            f[3].parse().unwrap_or(0),
            uid,
        ));
    }
    out
}

fn user_processes() -> usize {
    let me = unsafe { libc::getuid() };
    processes().iter().filter(|p| p.3 == me).count()
}

/// Ends every process of the case whose session is `session`: those in
/// the session and every descendant of its leader, stopped first (so none
/// forks again while the rest are found), then killed. Swept again until a
/// sweep finds nothing: on Linux a `SIGSTOP` sent to one process does not
/// cancel a fork already under way, so its child can appear after the last
/// scan and outlive the kill.
fn contain(session: i32) {
    for _ in 0..50 {
        if !sweep(session) {
            return;
        }
    }
}

/// One stop-then-kill pass of [`contain`]; false when nothing was found.
fn sweep(session: i32) -> bool {
    use std::collections::HashSet;
    let me = std::process::id() as i32;
    let mut stopped: HashSet<i32> = HashSet::new();
    for _ in 0..200 {
        let procs = processes();
        let mut found: HashSet<i32> = procs
            .iter()
            .filter(|p| p.0 == session || p.2 == session)
            .map(|p| p.0)
            .collect();
        loop {
            let more: Vec<i32> = procs
                .iter()
                .filter(|p| !found.contains(&p.0) && found.contains(&p.1))
                .map(|p| p.0)
                .collect();
            if more.is_empty() {
                break;
            }
            found.extend(more);
        }
        found.retain(|&p| p > 1 && p != me);
        let new: Vec<i32> = found.difference(&stopped).copied().collect();
        if new.is_empty() {
            break;
        }
        for &p in &new {
            unsafe {
                libc::kill(p, libc::SIGSTOP);
            }
        }
        stopped.extend(new);
    }
    for &p in &stopped {
        unsafe {
            libc::kill(p, libc::SIGKILL);
        }
    }
    !stopped.is_empty()
}

/// One isolated place to run inputs: shims logging to `log`, a work dir.
struct Slot {
    root: PathBuf,
    bin: PathBuf,
    log: PathBuf,
    profile: Option<PathBuf>,
    /// Cases run so far: the current case's tag is `c<cases>`.
    cases: std::sync::atomic::AtomicU64,
}

fn write_exec(path: &Path, body: &str) {
    std::fs::write(path, body).unwrap();
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755)).unwrap();
}

fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

impl Slot {
    fn new(root: PathBuf) -> Slot {
        let bin = root.join("bin");
        std::fs::create_dir_all(&bin).unwrap();
        std::fs::create_dir_all(root.join("home")).unwrap();
        std::fs::create_dir_all(root.join("tmp")).unwrap();
        std::fs::create_dir_all(root.join("zdot")).unwrap();
        let log = root.join("log");
        let logq = sh_quote(&log.display().to_string());
        // One write per record, so commands running at once do not
        // interleave. A record starts with the tag of the case that ran it,
        // so one written late by a process of an earlier case is told apart.
        let record = format!(
            "s=\"${{{CASE_VAR}-}}{TAG}${{0##*/}}\"\nfor a in \"$@\"; do s=\"$s{US}$a\"; done\nprintf '%s{RS}' \"$s\" >> {logq}\n"
        );
        for name in SHIMS {
            write_exec(&bin.join(name), &format!("#!/bin/sh\n{record}exit 0\n"));
        }
        let mut exec_allowed = vec![
            "/bin/sh".to_string(),
            "/bin/bash".into(),
            "/bin/zsh".into(),
            "/bin/dash".into(),
        ];
        for (name, candidates) in PASS_THROUGH {
            let Some(real) = candidates.iter().find(|p| Path::new(p).exists()) else {
                continue;
            };
            exec_allowed.push(real.to_string());
            write_exec(
                &bin.join(name),
                &format!("#!/bin/sh\n{record}exec {real} \"$@\"\n"),
            );
        }
        let handler = |fname: &str| {
            format!(
                "{fname}() {{ s=\"${{{CASE_VAR}-}}{TAG}{NOT_FOUND}$1\"; shift; for a in \"$@\"; do s=\"$s{US}$a\"; done; printf '%s{RS}' \"$s\" >> {logq}; return 127; }}\n"
            )
        };
        std::fs::write(root.join("bashenv"), handler("command_not_found_handle")).unwrap();
        std::fs::write(
            root.join("zdot/.zshenv"),
            handler("command_not_found_handler"),
        )
        .unwrap();
        let profile = Path::new("/usr/bin/sandbox-exec").exists().then(|| {
            let real_root = std::fs::canonicalize(&root).unwrap();
            let r = real_root.display().to_string();
            let mut p = format!(
                "(version 1)\n(allow default)\n(deny network*)\n(deny file-write* (subpath \"/\"))\n\
                 (allow file-write* (subpath \"{r}\") (literal \"/dev/null\") (literal \"/dev/tty\") \
                 (regex #\"^/dev/fd/\") (regex #\"^/dev/ttys\") (literal \"/dev/ptmx\"))\n\
                 (deny file-write* (subpath \"{r}/bin\") (subpath \"{r}/zdot\") (literal \"{r}/bashenv\") \
                 (literal \"{r}/profile.sb\"))\n(deny process-exec*)\n\
                 (allow process-exec* (subpath \"{r}/bin\")"
            );
            let shells = SHELLS.iter().map(|(_, s)| s.to_string());
            for e in exec_allowed.iter().cloned().chain(shells) {
                p.push_str(&format!(" (literal \"{e}\")"));
                // The sandbox checks the program a symlink resolves to.
                if let Ok(real) = std::fs::canonicalize(&e) {
                    p.push_str(&format!(" (literal \"{}\")", real.display()));
                }
            }
            p.push_str(")\n");
            let path = root.join("profile.sb");
            std::fs::write(&path, p).unwrap();
            path
        });
        Slot {
            root,
            bin,
            log,
            profile,
            cases: std::sync::atomic::AtomicU64::new(0),
        }
    }

    fn work(&self) -> PathBuf {
        self.root.join("work")
    }

    /// Fresh work dir with a few files for globs and `source`-free fixtures,
    /// and fresh home and temporary folders: nothing a case writes changes
    /// how a later one runs. (The shims and shell startup files cannot be
    /// written under the sandbox.)
    fn reset(&self) {
        for d in ["home", "tmp"] {
            let _ = std::fs::remove_dir_all(self.root.join(d));
            std::fs::create_dir_all(self.root.join(d)).unwrap();
        }
        let work = self.work();
        let _ = std::fs::remove_dir_all(&work);
        std::fs::create_dir_all(work.join("sub")).unwrap();
        for f in ["f1", "f2.txt", "rm", ".hidden"] {
            std::fs::write(work.join(f), "x\n").unwrap();
        }
        let _ = std::fs::remove_file(&self.log);
    }

    fn files(&self) -> BTreeSet<String> {
        fn walk(dir: &Path, base: &Path, out: &mut BTreeSet<String>) {
            let Ok(rd) = std::fs::read_dir(dir) else {
                return;
            };
            for e in rd.flatten() {
                let p = e.path();
                let rel = p.strip_prefix(base).unwrap().display().to_string();
                if e.file_type().map(|t| t.is_dir()).unwrap_or(false) {
                    walk(&p, base, out);
                }
                out.insert(rel);
            }
        }
        let mut out = BTreeSet::new();
        walk(&self.work(), &self.work(), &mut out);
        out
    }

    /// Run `input` under `shell`; the argv of every logged command and the
    /// files the run created.
    fn run(&self, label: &str, shell: &str, input: &str) -> Run {
        let _shared = RUNS.read().unwrap_or_else(|e| e.into_inner());
        self.run_case(label, shell, input)
    }

    fn run_case(&self, label: &str, shell: &str, input: &str) -> Run {
        let case = self
            .cases
            .fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        self.reset();
        let before = self.files();
        let mut cmd = match &self.profile {
            Some(p) => {
                let mut c = Command::new("/usr/bin/sandbox-exec");
                c.arg("-f").arg(p).arg(shell);
                c
            }
            None => Command::new(shell),
        };
        cmd.arg("-c")
            .arg(input)
            .env_clear()
            .env("PATH", &self.bin)
            .env("HOME", self.root.join("home"))
            .env("TMPDIR", self.root.join("tmp"))
            .env("LC_ALL", "C")
            .env(CASE_VAR, format!("c{case}"))
            .current_dir(self.work())
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::piped());
        // Each case runs in a session of its own, under a process budget.
        let cap = (user_processes() + CASE_PROCESSES) as libc::rlim_t;
        unsafe {
            cmd.pre_exec(move || {
                if libc::setsid() < 0 {
                    return Err(std::io::Error::last_os_error());
                }
                let limit = libc::rlimit {
                    rlim_cur: cap,
                    rlim_max: cap,
                };
                if libc::setrlimit(libc::RLIMIT_NPROC, &limit) < 0 {
                    return Err(std::io::Error::last_os_error());
                }
                Ok(())
            });
        }
        if label.starts_with("bash") {
            cmd.env("BASH_ENV", self.root.join("bashenv"));
        }
        if label == "zsh" {
            cmd.env("ZDOTDIR", self.root.join("zdot"));
        }
        let mut child = cmd.spawn().expect("spawn shell");
        let session = child.id() as i32;
        let mut stderr = child.stderr.take().unwrap();
        let reader = std::thread::spawn(move || {
            let mut s = Vec::new();
            let _ = (&mut stderr).take(64 * 1024).read_to_end(&mut s);
            String::from_utf8_lossy(&s).into_owned()
        });
        let deadline = Instant::now() + Duration::from_secs(4);
        let mut timed_out = false;
        let mut over_limit = false;
        let mut polls = 0usize;
        loop {
            if child.try_wait().unwrap().is_some() {
                break;
            }
            polls += 1;
            if polls.is_multiple_of(4)
                && processes().iter().filter(|p| p.2 == session).count() > CASE_LIMIT
            {
                timed_out = true;
                over_limit = true;
                contain(session);
                let _ = child.wait();
                break;
            }
            if Instant::now() > deadline {
                timed_out = true;
                contain(session);
                let _ = child.wait();
                break;
            }
            std::thread::sleep(Duration::from_millis(2));
        }
        // Background jobs may still write; give them a moment, then end them.
        if input.contains('&') || input.contains("coproc") {
            std::thread::sleep(Duration::from_millis(40));
        }
        contain(session);
        let stderr = if timed_out {
            String::new()
        } else {
            reader.join().unwrap_or_default()
        };
        let log = std::fs::read_to_string(&self.log).unwrap_or_default();
        let mut stale = false;
        let argvs = log
            .split(RS)
            .filter(|r| !r.is_empty())
            .filter_map(|r| {
                // A record an input wrote to the log itself has no tag: kept.
                let Some((tag, rest)) = r.split_once(TAG) else {
                    return Some(r);
                };
                // An earlier case's tag: a process of that case outlived it.
                let earlier = tag
                    .strip_prefix('c')
                    .and_then(|n| n.parse::<u64>().ok())
                    .is_some_and(|n| n < case);
                stale |= earlier;
                (!earlier).then_some(rest)
            })
            .map(|r| r.split(US).map(str::to_string).collect())
            .collect();
        let created = self.files().difference(&before).cloned().collect();
        let starved = [
            "fork: ",
            "Resource temporarily unavailable",
            "No space left",
        ];
        let inconclusive = if over_limit {
            Some("over the process limit")
        } else if timed_out {
            Some("timed out")
        } else if starved.iter().any(|s| stderr.contains(s)) {
            Some("out of processes or disk space")
        } else if stale {
            Some("an earlier case's process wrote to the log")
        } else {
            None
        };
        Run {
            argvs,
            created,
            stderr,
            inconclusive,
        }
    }
}

struct Run {
    argvs: Vec<Vec<String>>,
    created: Vec<String>,
    #[allow(dead_code)]
    stderr: String,
    /// Why the run may not show what the input does: it was cut short
    /// (timed out, or stopped over the process budget), a fork or a write
    /// failed for want of processes or disk space, or a process of an
    /// earlier case logged into it. What such a run logged did run, but a
    /// load-dependent failure can change what a shell does next, so a
    /// finding from it is checked by running the input again.
    inconclusive: Option<&'static str>,
}

/// What the scanner decided about an input.
enum Verdict {
    /// Not analyzable: the tool refuses it.
    Refused,
    /// Runs only when no rule could deny it.
    Dynamic,
    /// Checked command by command against these resources and writes.
    Checked {
        resources: Vec<String>,
        writes: Vec<Option<String>>,
        /// `cd` targets: a relative write may land under any of them.
        dirs: Vec<String>,
        redirect_only: bool,
    },
}

fn verdict(input: &str, cwd: &Path) -> Verdict {
    match shell_scan::analyze(input, cwd) {
        Err(_) => Verdict::Refused,
        Ok(a) if a.dynamic.is_some() => Verdict::Dynamic,
        Ok(a) => {
            // Zsh's reading of `((...))` as subshells may hold one too.
            let redirect_only = a
                .commands
                .iter()
                .chain(&a.delegated)
                .chain(&a.deny_only)
                .any(|(r, _)| {
                    r.trim_start()
                        .trim_start_matches(|c: char| c.is_ascii_digit())
                        .trim_start_matches('&')
                        .starts_with(['<', '>'])
                });
            Verdict::Checked {
                resources: a
                    .commands
                    .into_iter()
                    .chain(a.delegated)
                    .chain(a.deny_only)
                    .map(|(r, _)| r)
                    .collect(),
                writes: a.writes.into_iter().map(|w| w.path).collect(),
                dirs: a.directories,
                redirect_only,
            }
        }
    }
}

#[derive(Debug, Clone)]
struct Bypass {
    input: String,
    shell: String,
    what: String,
}

/// Every logged command or created file the scan does not account for.
fn bypasses(slot: &Slot, shells: &[(&str, &str)], input: &str) -> Vec<Bypass> {
    let work = slot.work();
    let v = verdict(input, &work);
    let (resources, writes, dirs, redirect_only) = match &v {
        Verdict::Refused | Verdict::Dynamic => return Vec::new(),
        // Inline code (`perl -e`, `awk '{system($0)}'`) is checked as the
        // resource `code:NAME ...`, which only a rule naming it allows: what
        // the code runs or writes is its own business, like a script's.
        Verdict::Checked { resources, .. } if resources.iter().any(|r| r.starts_with("code:")) => {
            return Vec::new()
        }
        // Sourcing a file runs it like a script, which the scan leaves to
        // the file (the shims are shell scripts: `. ../bin/rm` runs one).
        Verdict::Checked { resources, .. }
            if resources
                .iter()
                .any(|r| r.starts_with(". ") || r.starts_with("source ")) =>
        {
            return Vec::new()
        }
        Verdict::Checked {
            resources,
            writes,
            dirs,
            redirect_only,
        } => (resources, writes, dirs, *redirect_only),
    };
    let mut bases = vec![work.clone()];
    bases.extend(dirs.iter().map(|d| normalize(&work.join(d))));
    // What `run` (of `label`) did that the scan does not account for.
    let unaccounted = |label: &str, run: &Run| -> Vec<Bypass> {
        let mut out = Vec::new();
        for argv in &run.argvs {
            let (lookup, argv0) = match argv[0].strip_prefix(NOT_FOUND) {
                Some(n) => (true, n),
                None => (false, argv[0].as_str()),
            };
            let name = argv0.rsplit('/').next().unwrap_or(argv0).to_string();
            // A name looked up and not found ran nothing; it matters only if
            // a PATH could hold it and the input spells it (not `exec -a`'s
            // argv[0], or a word a shell reads differently).
            let argv0_set =
                input.contains("ARGV0") || resources.iter().any(|r| r.contains("exec -"));
            if lookup && (implausible(&name) || argv0_set || !input.contains(name.as_str())) {
                continue;
            }
            let pattern = format!("{name} *");
            if resources
                .iter()
                .any(|r| wildcard::matches(r, &pattern, false))
            {
                continue;
            }
            // Git reaching a remote runs `ssh` itself, as the program it is.
            if name == "ssh"
                && argv.last().is_some_and(|a| {
                    a.starts_with("git-upload-pack") || a.starts_with("git-receive-pack")
                })
                && resources
                    .iter()
                    .any(|r| wildcard::matches(r, "git *", false))
            {
                continue;
            }
            // Zsh runs `$NULLCMD`/`$READNULLCMD` (cat, more) for a bare redirect.
            if label == "zsh"
                && redirect_only
                && argv.len() == 1
                && ["cat", "more", "pager"].contains(&name.as_str())
            {
                continue;
            }
            out.push(Bypass {
                input: input.to_string(),
                shell: label.to_string(),
                what: format!("ran {argv:?}"),
            });
        }
        let unknown_write = writes.iter().any(Option::is_none);
        for f in &run.created {
            if f.starts_with("sh-thd-") {
                // Bash 3.2's here-document temp file, left after a syntax error.
                continue;
            }
            // BSD `sed -i`'s copy of a file it edits (`.!123!f1`), left
            // when the script fails: a write to the file itself.
            let sed_copy = f.rsplit('/').next().and_then(|n| {
                let rest = n.strip_prefix(".!")?;
                let (pid, name) = rest.split_once('!')?;
                pid.chars().all(|c| c.is_ascii_digit()).then_some(name)
            });
            if sed_copy.is_some_and(|name| {
                writes
                    .iter()
                    .flatten()
                    .any(|w| w.rsplit('/').next() == Some(name))
            }) {
                continue;
            }
            let abs = work.join(f);
            let named = writes.iter().flatten().any(|w| {
                bases.iter().any(|b| {
                    let target = normalize(&b.join(w));
                    // Dash does not expand `~+`: `> ~+` writes `./~+`.
                    target == normalize(&abs)
                        || (target.is_dir()
                            && normalize(&abs).parent() == Some(target.as_path())
                            && f.rsplit('/').next().is_some_and(|n| n.starts_with('~')))
                })
            });
            if !named && !unknown_write {
                out.push(Bypass {
                    input: input.to_string(),
                    shell: label.to_string(),
                    what: format!("wrote {f}"),
                });
            }
        }
        out
    };
    let mut out = Vec::new();
    for &(label, shell) in shells {
        // A finding from an inconclusive run is checked by running again:
        // a clean run decides. Found in every run, it is reported (what
        // was logged did run), saying the runs were inconclusive.
        for attempt in 1..=ATTEMPTS {
            let run = slot.run(label, shell, input);
            let found = unaccounted(label, &run);
            match run.inconclusive {
                Some(_) if !found.is_empty() && attempt < ATTEMPTS => continue,
                Some(why) => out.extend(found.into_iter().map(|mut b| {
                    b.what = format!("{} (inconclusive: {why}, in {ATTEMPTS} runs)", b.what);
                    b
                })),
                None => out.extend(found),
            }
            break;
        }
    }
    out
}

/// A name only the not-found handler logs, which no program on a real PATH
/// has: a shell that disagrees with the scan on how to spell a word looked
/// it up (`-p` after Zsh's `time`, `$rm` for `$"rm"`), and found nothing.
fn implausible(name: &str) -> bool {
    !SHIMS.contains(&name)
        && !PASS_THROUGH.iter().any(|(n, _)| *n == name)
        && (name.is_empty()
            || name.starts_with('-')
            || name.chars().all(|c| c.is_ascii_digit())
            || !name
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || "._+-".contains(c)))
}

fn normalize(p: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for c in p.components() {
        match c {
            std::path::Component::ParentDir => {
                out.pop();
            }
            std::path::Component::CurDir => {}
            c => out.push(c),
        }
    }
    out
}

