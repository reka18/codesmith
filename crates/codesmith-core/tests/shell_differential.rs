struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        // xorshift64*
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
    fn pick<'a>(&mut self, xs: &[&'a str]) -> &'a str {
        xs[self.below(xs.len())]
    }
}

fn squote(s: &str) -> String {
    sh_quote(s)
}

fn dquote(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        if "\"$`\\".contains(c) {
            o.push('\\');
        }
        o.push(c);
    }
    o.push('"');
    o
}

const LEAVES: &[&str] = &["touch", "rm", "curl", "git", "cat", "wget", "chmod"];

/// A spelling of command name `n` the shell resolves to `n`.
fn name_form(r: &mut Rng, n: &str) -> String {
    let (a, b) = n.split_at(1);
    match r.below(24) {
        16 => format!("={n}"),
        17 => format!("$'\\{:o}'{b}", a.as_bytes()[0]),
        18 => format!("noglob {n}"),
        19 => format!("coproc {n}"),
        20 => format!("time X=1 {n}"),
        21 => format!("env -- X=1 {n}"),
        22 => format!("~+/../bin/{n}"),
        23 => format!("nocorrect {n}"),
        0 => format!("{a}''{b}"),
        1 => format!("\\{n}"),
        2 => format!("\"{n}\""),
        3 => format!("$'{n}'"),
        4 => format!("$'\\x{:02x}'{b}", a.as_bytes()[0]),
        5 => format!("../bin/{n}"),
        6 => format!("../b?n/{n}"),
        7 => format!("{{{n},}}"),
        8 => format!("$(echo {n})"),
        9 => format!("`echo {n}`"),
        10 => format!("{a}\\\n{b}"),
        11 => format!("$'{a}'{b}"),
        12 => format!("command {n}"),
        13 => format!("X=1 {n}"),
        14 => format!("{a}\"\"{b}"),
        _ => n.to_string(),
    }
}

fn leaf(r: &mut Rng) -> String {
    let n = r.pick(LEAVES);
    let arg = r.pick(&["F", "-rf F", "http://x", "status", "f1"]);
    if r.below(3) == 0 {
        format!("{} {arg}", name_form(r, n))
    } else {
        format!("{n} {arg}")
    }
}

/// A command that runs `inner` somewhere inside it.
fn wrap(r: &mut Rng, inner: &str, depth: usize) -> String {
    let other = if depth > 0 && r.below(2) == 0 {
        gen(r, depth - 1)
    } else {
        "true".into()
    };
    match r.below(64) {
        48 => format!("echo \"${{x:-'$({inner})'}}\""),
        49 => format!("a=($({inner}))"),
        50 => format!("a=([$({inner})]=1)"),
        51 => format!("cat <<EOF\nEO\\\nF\n{inner}\nEOF"),
        52 => format!("x=$(printf %s {}); eval \"$x\"", squote(inner)),
        53 => format!("echo \"$\\\n({inner})\""),
        54 => format!("{{ {inner}; }} 2>/dev/null"),
        55 => format!("case x in *) {inner};; esac"),
        56 => format!("[[ x == x && -n $({inner}) ]]"),
        57 => format!("exec 3< <({inner})"),
        58 => format!(": ${{x:=$({inner})}}"),
        59 => format!(": \"${{x[$({inner})]}}\""),
        60 => format!("echo {} | sh", squote(inner)),
        61 => format!("cat <<EOF\n$(cat <<X\n$({inner})\nX\n)\nEOF"),
        62 => format!("x=1; echo \"${{x:+'$({inner})'}}\""),
        63 => format!("if ! {inner}; then :; fi"),
        0 => format!("( {inner} )"),
        1 => format!("{{ {inner}; }}"),
        2 => format!("if {other}; then {inner}; fi"),
        3 => format!("while {inner}; do break; done"),
        4 => format!("for i in 1; do {inner}; done"),
        5 => format!("case x in x) {inner};; esac"),
        6 => format!("case $({inner}) in *) ;; esac"),
        7 => format!("f() {{ {inner}; }}; f"),
        8 => format!("{other} | {inner}"),
        9 => format!("{other} && {inner}"),
        10 => format!("false || {inner}"),
        11 => format!("! {inner}"),
        12 => format!("eval {}", squote(inner)),
        13 => format!("bash -c {}", squote(inner)),
        14 => format!("sh -c {}", dquote(inner)),
        15 => format!("env {inner}"),
        16 => format!("x=$({inner})"),
        17 => format!("[[ -n $({inner}) ]]"),
        18 => format!("(( $({inner}) ))"),
        19 => format!("cat <<EOF\n$({inner})\nEOF"),
        20 => format!("time {inner}"),
        21 => format!("echo `{inner}`"),
        22 => format!("echo \"$({inner})\""),
        23 => format!("cat <({inner})"),
        24 => format!("echo ${{x:-$({inner})}}"),
        25 => format!("echo $((1+$({inner})))"),
        26 => format!("declare a[$({inner})]=1"),
        27 => format!("trap {} EXIT", squote(inner)),
        28 => format!("exec {inner}"),
        29 => format!("{inner} &"),
        30 => format!("until {inner}; do break; done"),
        31 => format!("echo x > $({inner})"),
        32 => format!("for x in $({inner}); do :; done"),
        33 => format!("select x in $({inner}); do break; done </dev/null"),
        34 => format!("xargs {inner}"),
        35 => format!("nice {inner}"),
        36 => format!("{other}; {inner}"),
        37 => format!("{other}\n{inner}"),
        38 => format!("function g {{ {inner}; }}; g"),
        39 => format!("x={}; eval \"$x\"", squote(inner)),
        40 => format!("zsh -c {}", squote(inner)),
        41 => format!("y=$(( $({inner}) ))"),
        42 => format!("[ \"$({inner})\" ]"),
        43 => format!("coproc {inner}"),
        44 => format!("echo ${{#x[$({inner})]}}"),
        45 => format!("printf -v v %s \"$({inner})\""),
        46 => format!("read -r v <<< \"$({inner})\""),
        _ => format!("{inner} 2>&1 | cat"),
    }
}

fn gen(r: &mut Rng, depth: usize) -> String {
    let mut s = leaf(r);
    let layers = 1 + r.below(depth.max(1));
    for _ in 0..layers {
        s = wrap(r, &s, depth.saturating_sub(1));
    }
    s
}

