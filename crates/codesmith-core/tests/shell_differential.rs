/// Small edits that change how a shell lexes text.
const MUTATIONS: &[&str] = &[
    "\\\n", "''", "\"\"", "\\", "$", " ", "\t", "\n", ";", "(", ")", "{", "}", "`", "'", "\"", "#",
    "=", "[", "]", "$'", "<<", "|", "&",
];

fn mutate(r: &mut Rng, input: &str) -> String {
    let mut chars: Vec<char> = input.chars().collect();
    for _ in 0..1 + r.below(3) {
        let at = r.below(chars.len() + 1);
        match r.below(4) {
            0 if at < chars.len() => {
                chars.remove(at);
            }
            1 if at < chars.len() => {
                let c = chars[at];
                chars.insert(at, c);
            }
            _ => {
                let m = r.pick(MUTATIONS);
                for (k, c) in m.chars().enumerate() {
                    chars.insert(at + k, c);
                }
            }
        }
    }
    chars.into_iter().collect()
}

/// Corpus inputs with random lexical edits. Mutations can spell any
/// command line, so this runs only inside the macOS sandbox.
#[test]
fn shell_differential_mutated() {
    let cases: usize = std::env::var("CODESMITH_FUZZ_MUTATIONS")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(300);
    let seed: u64 = std::env::var("CODESMITH_FUZZ_SEED")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(0x5eed_c0de);
    let (_dir, slots) = slots(workers());
    if slots[0].profile.is_none() {
        eprintln!("shell_differential_mutated: no sandbox-exec, skipped");
        return;
    }
    let seeds: Vec<String> = corpus()
        .into_iter()
        .filter(|c| c.known.is_none())
        .map(|c| c.input)
        .collect();
    let mut rng = Rng(seed.rotate_left(17) | 1);
    let inputs: Vec<String> = (0..cases)
        .map(|_| loop {
            let base = &seeds[rng.below(seeds.len())];
            let m = mutate(&mut rng, base);
            // A redefined not-found handler runs for every unknown name,
            // itself included: such a case proves nothing about the scan,
            // and only the process budget would end it.
            if !m.contains("not_found_handle") {
                break m;
            }
        })
        .collect();
    let results = run_all(&slots, &inputs);
    let found: Vec<Bypass> = results.into_iter().flat_map(|(_, b)| b).collect();
    assert!(
        found.is_empty(),
        "mutated bypasses (seed {seed}):\n{}",
        report(&found)
    );
}

/// A case that forks without end finishes quickly and leaves nothing
/// running: the process budget stops its forks, the sweep ends the rest.
#[test]
fn shell_differential_contains_fork_bombs() {
    const BOMB: &str = "command_not_found_handler() { rr|m F; }; nosuch";
    const BASH_BOMB: &str = "command_not_found_handle() { rr|m F; }; nosuch";
    let (_dir, slots) = slots(1);
    // Alone, so no other case's processes are counted or match.
    let _alone = RUNS.write().unwrap_or_else(|e| e.into_inner());
    let before = user_processes();
    for &(label, shell) in &installed_shells() {
        for input in [BOMB, BASH_BOMB, "f() { f | f; }; f"] {
            let start = Instant::now();
            slots[0].run_case(label, shell, input);
            assert!(start.elapsed() < Duration::from_secs(8), "{label}: {input}");
            // A killed process can show in `ps` for a moment while it exits,
            // longer on a loaded machine; one that is still there after the
            // deadline leaked.
            let still_running = || -> Vec<String> {
                let ps = Command::new("/bin/ps")
                    .args(["-A", "-o", "command="])
                    .output()
                    .expect("ps");
                String::from_utf8_lossy(&ps.stdout)
                    .lines()
                    // A shell (or subshell) of the case: `SHELL -c INPUT`.
                    .filter(|l| {
                        l.split_once(" -c ")
                            .is_some_and(|(_, code)| code.trim_end() == input)
                    })
                    .map(str::to_string)
                    .collect()
            };
            let deadline = Instant::now() + Duration::from_secs(5);
            let mut left = still_running();
            while !left.is_empty() && Instant::now() < deadline {
                std::thread::sleep(Duration::from_millis(50));
                left = still_running();
            }
            assert!(left.is_empty(), "{label}: still running: {left:?}");
        }
    }
    // Other work on the machine changes the count too: only a leak of the
    // budget's size would show.
    assert!(
        user_processes() < before + CASE_PROCESSES,
        "{} processes before, {} after",
        before,
        user_processes()
    );
}

/// Sanity: the harness sees commands, so an empty log means something.
#[test]
fn shell_differential_harness_observes() {
    let (_dir, slots) = slots(1);
    let shells = installed_shells();
    assert!(!shells.is_empty());
    for &(label, shell) in &shells {
        let run = slots[0].run(
            label,
            shell,
            "touch a; $(echo rm) b; echo x > out; nosuchcmd q",
        );
        let names: Vec<&str> = run.argvs.iter().map(|a| a[0].as_str()).collect();
        assert!(
            names.contains(&"touch"),
            "{label}: {names:?} {}",
            run.stderr
        );
        assert!(names.contains(&"rm"), "{label}: {names:?}");
        assert!(run.created.contains(&"out".to_string()), "{label}");
        if label == "bash" || label == "zsh" {
            assert!(names.contains(&"\u{1}nosuchcmd"), "{label}: {names:?}");
        }
    }
    // The scan reports `$(echo rm) b` as dynamic; a static one is checked.
    let found = bypasses(&slots[0], &shells, "touch a; rm b");
    assert!(found.is_empty(), "{}", report(&found));

    // A record tagged with an earlier case (a process that outlived it) is
    // not counted, and makes the run inconclusive.
    if let Some(&(label, shell)) = shells.iter().find(|(l, _)| *l == "bash") {
        let run = slots[0].run(
            label,
            shell,
            "builtin printf 'c0\\002rm\\037F\\036' >> ../log; touch a",
        );
        let names: Vec<&str> = run.argvs.iter().map(|a| a[0].as_str()).collect();
        assert_eq!(names, ["touch"]);
        assert!(run.inconclusive.is_some());
    }
    // Under the sandbox no case can change the shims or the startup files
    // a later case runs with, and each starts with an empty home.
    if slots[0].profile.is_some() {
        let shim = std::fs::read_to_string(slots[0].bin.join("rm")).unwrap();
        let bashenv = std::fs::read_to_string(slots[0].root.join("bashenv")).unwrap();
        for &(label, shell) in &shells {
            let run = slots[0].run(
                label,
                shell,
                "echo x > ../bin/rm; echo x >> ../bashenv; echo x > ../zdot/.zshenv; echo x > ~/f",
            );
            assert!(run.inconclusive.is_none(), "{label}");
            assert_eq!(
                std::fs::read_to_string(slots[0].bin.join("rm")).unwrap(),
                shim
            );
            assert_eq!(
                std::fs::read_to_string(slots[0].root.join("bashenv")).unwrap(),
                bashenv
            );
        }
        slots[0].reset();
        assert!(!slots[0].root.join("home/f").exists());
    }
}
